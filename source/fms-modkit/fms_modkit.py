"""FMS ModKit — Fantasy Map Simulator 本地 Mod 工具包.

基于对游戏官方 Mods 加载机制的分析（reports/game-architecture.md §4）：
  - 游戏按 Base / Mods / SteamWorkshop 三层加载 Culture/Religion/Military 等数据包
  - 本地 Mods 优先级高于 Workshop（游戏内冲突提示原文）
  - 文化包格式：CultureData.json + StateNames.csv + CityNames.csv + Character*.csv

本工具只写入游戏用户数据目录（persistentDataPath），绝不修改原版安装目录。

用法示例：
  python fms_modkit.py new-culture Auroria --display "奥瑞利亚" --out ./packs/Auroria
  python fms_modkit.py install-culture ./packs/Auroria
  python fms_modkit.py list-mods
  python fms_modkit.py config backup
  python fms_modkit.py config set isAllowCivilWar false
  python fms_modkit.py config set minMonthToBeginAnotherWar 6
  python fms_modkit.py config get isAllowCivilWar
"""
