def _write_csv(path, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        for r in rows:
            w.writerow([r])


# 游戏名称 CSV 为 15 列多语言表头格式（列数不符的行会被跳过，见 Player.log 实测）
NAME_CSV_HEADER = ["Key", "Chinese", "English", "TraditionalChinese", "Russian",
                   "SpanishSpain", "PortugueseBrazil", "German", "Japanese", "French",
                   "Polish", "SpanishLatinAmerica", "PortuguesePortugal", "Korean", "Turkish"]


def _write_names_csv(path, rows, key_prefix=None):
    """rows: 纯名字列表；Key=Chinese=English=名字，其余语言留空（与 Workshop 包做法一致）。"""
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(NAME_CSV_HEADER)
        for i, name in enumerate(rows, 1):
            key = f"{key_prefix}_{i}" if key_prefix else name
            w.writerow([key, name, name] + [""] * 12)


def cmd_new_culture(args):
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    name, display = args.name, args.display or args.name
    data = json.loads(json.dumps(CULTURE_TEMPLATE).replace("{name}", name).replace("{display}", display))
    if args.color:
        data["CultureColorHex"] = args.color
    if args.desc:
        data["CultureDescriptionTranslations"] = [args.desc,
                                                  f"{name}: {args.desc}"]
    with open(os.path.join(out, "CultureData.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    _write_names_csv(os.path.join(out, "StateNames.csv"), [n.format(name=name) for n in DEFAULT_STATE_NAMES])
    _write_names_csv(os.path.join(out, "CityNames.csv"), [n.format(name=name) for n in DEFAULT_CITY_NAMES])
    _write_names_csv(os.path.join(out, "CharacterFirstNames_Male.csv"), DEFAULT_MALE, "MaleName")
    _write_names_csv(os.path.join(out, "CharacterFirstNames_Female.csv"), DEFAULT_FEMALE, "FemaleName")
    _write_names_csv(os.path.join(out, "CharacterLastNames.csv"), DEFAULT_LAST, "LastName")
    print(f"[ok] 文化包已生成: {out}")
    print("     安装命令: python fms_modkit.py install-culture " + out)


def cmd_install_culture(args):
    src = os.path.abspath(args.src)
    cd = os.path.join(src, "CultureData.json")
    if not os.path.exists(cd):
        sys.exit(f"[fail] 找不到 {cd}")
    with open(cd, encoding="utf-8-sig") as f:
        pack_name = json.load(f)["CultureName"]
    os.makedirs(MODS_CULTURE, exist_ok=True)
    dst = os.path.join(MODS_CULTURE, pack_name)
    if os.path.exists(dst):
        if not args.overwrite:
            sys.exit(f"[fail] 目标已存在: {dst}（--overwrite 覆盖）")
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    print(f"[ok] 已安装到游戏 Mods 目录: {dst}")
    print("     下一步：启动游戏 → 设置 → 文化面板，或用 `verify` 检查")


def cmd_list_mods(args):
    print("本地 Mods 目录:", MODS_ROOT)
    print("Mods/Culture 存在:", os.path.isdir(MODS_CULTURE))
    if os.path.isdir(MODS_CULTURE):
        for d in sorted(os.listdir(MODS_CULTURE)):
            print("  -", d)
    cfg = json.load(open(CONFIG_PATH, encoding="utf-8")) if os.path.exists(CONFIG_PATH) else {}
    print("gameConfig.json EnabledCultureIDs:", cfg.get("EnabledCultureIDs"))


def cmd_uninstall_culture(args):
    dst = os.path.join(MODS_CULTURE, args.name)
    if not os.path.isdir(dst):
        sys.exit(f"[fail] 未安装: {dst}")
    shutil.rmtree(dst)
    print(f"[ok] 已卸载: {dst}")


def cmd_config(args):
    os.makedirs(BACKUP_DIR, exist_ok=True)
    if args.action == "backup":
        stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        dst = os.path.join(BACKUP_DIR, f"gameConfig_{stamp}.json")
        shutil.copy2(CONFIG_PATH, dst)
        print("[ok] 已备份:", dst)
        return
    if not os.path.exists(CONFIG_PATH):
        sys.exit("[fail] 找不到 gameConfig.json（请先运行一次游戏）")
    cfg = json.load(open(CONFIG_PATH, encoding="utf-8"))
    if args.action == "get":
        print(json.dumps(cfg.get(args.key), ensure_ascii=False))
    elif args.action == "set":
        old = cfg.get(args.key)
        cur = cfg[args.key] if args.key in cfg else None
        val = json.loads(args.value)
        cfg[args.key] = val
        stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        shutil.copy2(CONFIG_PATH, os.path.join(BACKUP_DIR, f"gameConfig_{stamp}.json"))
        json.dump(cfg, open(CONFIG_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
        print(f"[ok] {args.key}: {old!r} -> {val!r}（原文件已备份）")
        print("注意：游戏运行时会以内存值覆盖此文件，请在游戏未运行时修改。")
    elif args.action == "keys":
        for k in sorted(cfg):
            print(f"  {k} = {json.dumps(cfg[k], ensure_ascii=False)}")


def main():
    ap = argparse.ArgumentParser(description="FMS ModKit")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new-culture"); p.add_argument("name"); p.add_argument("--display"); p.add_argument("--color"); p.add_argument("--desc"); p.add_argument("--out", required=True)
    p.set_defaults(fn=cmd_new_culture)
    p = sub.add_parser("install-culture"); p.add_argument("src"); p.add_argument("--overwrite", action="store_true")
    p.set_defaults(fn=cmd_install_culture)
    p = sub.add_parser("uninstall-culture"); p.add_argument("name")
    p.set_defaults(fn=cmd_uninstall_culture)
    p = sub.add_parser("list-mods"); p.set_defaults(fn=cmd_list_mods)
    p = sub.add_parser("config"); p.add_argument("action", choices=["backup", "get", "set", "keys"]); p.add_argument("key", nargs="?"); p.add_argument("value", nargs="?")
    p.set_defaults(fn=cmd_config)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
